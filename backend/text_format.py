"""
Приведение ответа модели к виду, пригодному для мобильного чат-виджета
(ТЗ v2, п. 3.6): виджет показывает текст как есть (textContent), поэтому
пользователь не должен видеть служебные символы Markdown (**, ##, ` и т.п.),
даже если модель всё-таки их вернула вопреки промпту.
"""
import re

# Маркер открывается не внутри слова и закрывается не внутри слова — иначе
# "t.me/agros_expo ... some_name" склеилось бы в курсив. Одна строка.
_BOLD_ITALIC = re.compile(r"(?<!\w)(\*\*\*|\*\*|__|\*|_)(?=\S)(.+?)(?<=\S)\1(?!\w)")


# Модель любит подставлять типографские символы: неразрывный дефис в телефоне
# ("758-0-911") и неразрывные пробелы ломают копирование номера/адреса и поиск
# по тексту — заменяем на обычные.
_TYPO = {"\u2011": "-", "\u2010": "-", "\u00a0": " ", "\u202f": " ", "\u2009": " "}


def clean_markdown(text: str) -> str:
    for src, dst in _TYPO.items():
        text = text.replace(src, dst)
    text = text.replace("\r\n", "\n")
    # Заголовки: "## Заголовок" -> "Заголовок"
    text = re.sub(r"^\s{0,3}#{1,6}\s*", "", text, flags=re.MULTILINE)
    # Жирный/курсив — оставляем только содержимое (несколько проходов для вложенных)
    for _ in range(3):
        text = _BOLD_ITALIC.sub(r"\2", text)
    # Остаточные одиночные маркеры вокруг слов и инлайн-код
    text = text.replace("**", "").replace("__", "").replace("`", "")
    # Маркированные списки -> короткое тире; нумерованные оставляем как есть
    text = re.sub(r"^\s*[-*•]\s+", "– ", text, flags=re.MULTILINE)
    # Ссылки вида [текст](url) -> "текст: url"
    text = re.sub(r"\[([^\]]+)\]\((https?://[^)\s]+)\)", r"\1: \2", text)
    # Хвостовые двойные пробелы (Markdown-перенос) и лишние пустые строки
    text = re.sub(r"[ \t]+\n", "\n", text)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


MORE_PHRASE = "Могу рассказать подробнее."


def shorten(text: str, limit: int = 650) -> str:
    """Страховка по длине (ТЗ v2, 3.6): если модель всё же написала слишком
    много для мобильного окна, режем по границе строки/предложения и
    предлагаем рассказать подробнее — детали не теряются, их можно запросить."""
    if len(text) <= limit:
        return text
    cut = text[:limit]
    for sep in ("\n", ". ", "; "):
        pos = cut.rfind(sep)
        if pos >= limit * 0.5:
            cut = cut[: pos + (0 if sep == "\n" else 1)]
            break
    else:
        cut = cut.rsplit(" ", 1)[0]
    return f"{cut.rstrip()}\n\n{MORE_PHRASE}"
