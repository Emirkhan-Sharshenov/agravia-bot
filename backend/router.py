# Темы, ответ на которые зависит от роли: если роль неизвестна — сначала
# уточняем (ТЗ 3.2), а не угадываем.
ROLE_DEPENDENT = {"pass", "badge", "entry", "vehicle_access"}

ROUTER_SYSTEM = """Ты — классификатор сообщений чат-бота выставки AGRAVIA 2027. По сообщению пользователя, \
истории и состоянию диалога определи тему (intent) и роль пользователя. Верни ТОЛЬКО JSON без пояснений:
{{"intent": "<тема>", "role": "<роль>"}}

РОЛИ:
visitor — посетитель/гость выставки
exhibitor — действующий экспонент/участник, который уже участвует
prospect — хочет стать участником/экспонентом, ещё не участвует
builder — застройщик, монтажная команда, подрядчик по монтажу/логистике
none — роль неизвестна

ПРАВИЛА РОЛИ: role — роль пользователя ПОСЛЕ этого сообщения. Если он явно называет или однозначно \
подразумевает роль — используй её, она заменяет прежнюю. Иначе оставь роль из состояния диалога; если и там \
её нет — none.

ТЕМЫ (intent):
{intents}

ПРАВИЛА ТЕМЫ:
- Короткое согласие, просьба «подробнее» или ответ на вопрос бота продолжают тему из состояния: \
если бот задал уточняющий вопрос — это pending_intent, иначе тема прошлого хода.
- Если пользователь исправляет себя («нет, я про …») — тема и роль берутся из исправления, оно заменяет прежние.
- Если пользователь переходит к соседнему аспекту того же круга вопросов — выбери тему этого аспекта.
- Если в сообщении есть конкретная тема — не используй help; help только когда конкретики нет совсем.

СОСТОЯНИЕ ДИАЛОГА:
{state}

ИСТОРИЯ (последние сообщения):
{history}
"""


@dataclass
class Route:
    intent: str
    role: str | None  # None — роль неизвестна


def _describe_state(state: dict) -> str:
    role = state.get("role") or "none"
    lines = [f"role: {role}", f"предыдущая тема: {state.get('intent') or 'нет'}"]
    pending = state.get("pending")
    if pending:
        lines.append(
            f"бот только что задал уточняющий вопрос ({pending['kind']}) по теме "
            f"pending_intent={pending.get('intent')}; сообщение пользователя — ответ на него"
        )
    return "\n".join(lines)


def _describe_history(history: list[dict]) -> str:
    if not history:
        return "(пусто)"
    lines = []
    for turn in history[-6:]:
        who = "пользователь" if turn.get("role") == "user" else "бот"
        text = (turn.get("content") or "").replace("\n", " ")
        lines.append(f"{who}: {text[:220]}")
    return "\n".join(lines)


def _parse(text: str) -> dict | None:
    match = re.search(r"\{.*?\}", text, re.DOTALL)
    if not match:
        return None
    try:
        data = json.loads(match.group(0))
    except json.JSONDecodeError:
        return None
    return data if isinstance(data, dict) else None


def classify(message: str, history: list[dict] | None, state: dict) -> Route:
    """Определяет тему и роль. Бросает исключение, если LLM недоступна или
    вернула нечитаемый ответ — вызывающий код сам решает, как деградировать."""
    system = ROUTER_SYSTEM.format(
        intents="\n".join(f"{k} — {v}" for k, v in INTENT_DESCRIPTIONS.items()),
        state=_describe_state(state),
        history=_describe_history(history or []),
    )
    text = llm.complete(system, [{"role": "user", "content": message}], max_tokens=500, temperature=0.0)
    data = _parse(text)
    if data is None:
        raise ValueError(f"router: нечитаемый ответ модели: {text[:200]!r}")

    intent = str(data.get("intent", "")).strip()
    if intent not in INTENT_DESCRIPTIONS:
        intent = "other"
    role = str(data.get("role", "")).strip().lower()
    if role not in ROLES:
        role = None
    return Route(intent=intent, role=role)
