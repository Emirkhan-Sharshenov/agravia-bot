"""
Определение намерения (intent) и роли пользователя (ТЗ v2, п. 3.1-3.3).

Сопоставление по словам/похожести строк не годится как основной механизм
понимания: разговорные и перефразированные формулировки одного и того же
вопроса ("где взять бейдж", "мне куда нажать, чтобы прийти") оно распознаёт
нестабильно. Поэтому намерение и роль определяет LLM по описаниям тем
(без примеров конкретных фраз — ни одна формулировка не зашита в код), с
учётом состояния диалога: ранее установленной роли, прошлой темы и
уточняющего вопроса, на который пользователь сейчас отвечает.
"""
from __future__ import annotations

import json
import re
from dataclasses import dataclass

import llm

ROLES = ("visitor", "exhibitor", "prospect", "builder")

